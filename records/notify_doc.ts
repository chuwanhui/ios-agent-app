/**
 * 「怎么接微信 / 钉钉」的说明文档。
 *
 * 放在这里而不是写进页面组件里：这是一段给人看的文案，改措辞不该动界面逻辑。
 * 页面只负责把它交给 Markdown 渲染。
 */

/** 给快捷指令用的最小 JSON 模板（一键拷贝的那段）。 */
export const NOTIFY_TEMPLATE_JSON = '{"app":"微信","sender":"张三","content":"明天几点开会？"}'

/**
 * 完整说明（Markdown）。
 * @param scriptName 本脚本在「快捷指令」里的名字，用来写「运行脚本」那一步选什么。
 */
export function notifyDocMarkdown(scriptName: string): string {
  const name = (scriptName ?? "").trim() || "智能体"
  return `## 它能做什么、不能做什么

iOS 不允许第三方脚本读取别的 App 的通知内容，所以**它不监听微信 / 钉钉**。分工是：

- **快捷指令**负责把消息原文交进来；
- **它**负责拿到消息之后的事：每个发件人单独的记忆、人设、知识库 / 技能 / 工具、失败重试、写进本页的记录。

它只产出**回复文本**，不会替你发出去（原因见最后一节）。

## 第一步：建一条快捷指令

1. 打开「快捷指令」App → 新建
2. 加动作 **「运行脚本」**，脚本选 \`${name}\`（入口是 \`intent.tsx\`）
3. 这个动作的**输入**填成文本，内容是一段 JSON（格式见下）；动作的**输出**就是回复
4. 后面接你想做的动作：「显示结果」、发通知、写文件、转发到群机器人……

## 第二步：输入格式

\`\`\`json
${NOTIFY_TEMPLATE_JSON}
\`\`\`

| 字段 | 必填 | 说明 | 也可以写成 |
| --- | --- | --- | --- |
| \`app\` | 是 | 来源 App，记忆按它分组 | \`sourceApp\` \`bundle\` \`package\` \`来源应用\` |
| \`sender\` | 是 | 发件人，记忆按它分组 | \`from\` \`user\` \`name\` \`发件人\` \`发送人\` |
| \`content\` | 是 | 消息正文 | \`message\` \`text\` \`body\` \`内容\` \`发件内容\` |
| \`messageId\` | 否 | 同一条消息的唯一 ID，有就填，去重更准 | \`msgId\` \`notificationId\` \`id\` \`消息ID\` |

前三项缺任何一项都不当通知处理，会退回成「普通聊天」（把整段输入当成一句话发给模型）。

## 第三步：消息从哪来

| 方式 | 自动化程度 | 怎么做 |
| --- | --- | --- |
| 手动 / 分享表单 | 半自动 | 复制消息，跑快捷指令，把正文填进 \`content\` |
| 个人自动化「打开某 App」 | 半自动 | 触发时跑一条脚本读剪贴板，你复制一下消息即可 |
| 第三方转发 | 全自动 | 让消息先落到某个能发 webhook / 能写文件的中间人，再由快捷指令取 |

系统层没有「收到某 App 的通知就触发」这种能力，只能走上面这些路。

## 送进来之后发生了什么

1. **入队**：立刻处理；一次处理不完的留在队列里，App 打开时会自动接着排空（一次最多跑 80 秒）。
2. **去重**：有 \`messageId\` 按 ID 判重；没有就用「App + 发件人 + 正文」当指纹。2 分钟内重复的丢掉，已经处理过的那条 7 天内再送也算重复。
3. **排队串行**：通知、App 打开、快捷指令三路同时进来，同一时刻只有一个消费者，不会重复回同一条。
4. **分段记忆**：按「App + 发件人」各用一段会话（标题自动叫「张三（微信）」），张三和李四的记忆互不串味。
5. **记忆维护**：超过 30 天没说话就清空重来；攒到 36 条自动压缩成一段摘要，只保留最近 14 条原文。
6. **跑一轮**：用设置里的模型 + 性格与角色 + 知识库 / 技能 / 工具（要动手就调对应工具）。
7. **记录**：完成的消息会出现在本页，按 App → 联系人分组。
8. **失败重试**：自动试 4 次，间隔 15 秒 / 1 分钟 / 3 分钟 / 10 分钟；4 次都失败就进本页的「处理失败」，可以手动重试或丢掉。

## 回复怎么发回去

脚本只把回复作为快捷指令的返回值交出来，发不发、发到哪由快捷指令决定：

- **钉钉群**：接「自定义机器人」webhook，把返回值 POST 出去，可以真自动回；
- **微信个人对话**：没有公开接口，实际只能弹通知提醒你自己发、或复制到剪贴板；
- **其它**：写进备忘录 / 发邮件 / 存文件都行。

## 常见问题

- **提示「请先填写 API Key」**：设置 → 模型配置里还没配好供应商，通知会原样留在队列里等着。
- **提示「消息已入队」**：这一轮没轮到它（超时或正在处理别的），下次触发或打开 App 会继续。
- **提示「已处理过同一条通知」**：被去重拦下了，确认是不是重复触发。
- **一直失败**：看本页「处理失败」里的错误摘要，多半是网络或模型返回出错；点「重试」再试一次。
`
}
