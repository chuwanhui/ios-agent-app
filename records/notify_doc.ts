import { messageRunURL } from "../core/agent/url_entry"

/** 给快捷指令用的最小 JSON 模板（一键拷贝的那段）。 */
export const NOTIFY_TEMPLATE_JSON = '{"app":"微信","sender":"张三","content":"明天几点开会？"}'

/**
 * 「怎么把消息送进来」这段说明（URL 入口）。
 *
 * 两处共用同一份文字：整份通知文档里内嵌一份，消息记录页也单独摊一份。
 * 讲的是**推荐路径**：用「打开 URL」把 App 拉到前台，而不是「运行脚本」——
 * 后台进程在 iOS 上根本拉不起别的 App，AI 想发消息就必然失败。
 */
export function urlEntryDoc(scriptName: string): string {
  const base = messageRunURL(scriptName, "")
  return `## 怎么把消息送进智能体

推荐用「打开 URL」，不要用「运行脚本」：

1. 快捷指令里加动作 **「打开 URL」**；
2. 内容填：

   \`${base}?message=<URL 编码后的文本>\`

3. 运行时会打开 Scripting，AI 在**前台**把这条消息处理掉。

为什么强调前台：它要动手时（发微信、发钉钉、发通知）需要去拉起别的快捷指令，
而 iOS **不允许后台进程拉别的 App**。「运行脚本」是后台进程，所以那种方式下 AI
永远调不动快捷指令；「打开 URL」把 App 拉到前台就没这个问题了。

### 传一段普通文本

\`${base}?message=%E5%B8%AE%E6%88%91%E7%9C%8B%E7%9C%8B%E4%BB%8A%E5%A4%A9%E7%9A%84%E5%AE%89%E6%8E%92\`

（就是「帮我看看今天的安排」编码后的样子。中文和空格必须编码，否则会被 URL 截断。）

### 传一条通知

\`message\` 里放上一节那套 JSON，整段编码后塞进去，例如原文是：

\`\`\`json
{"app":"微信","sender":"张三","content":"晚上一起吃饭吗"}
\`\`\`

它会按**通知**处理：

- **「App + 发件人」锁定一条会话**：微信里的张三永远落在「张三（微信）」这条里，
  和李四的消息互不串味；
- 打开链接时 App 直接**跳转到这条会话**，消息和回复都在那儿，看得见；
- 同一条处理过会去重，重复打开只跳过去看历史，不会重复回一遍；
- 处理完还会写进「记录」页，按 App → 联系人分组。

不是合法 JSON、或缺 \`app\` / \`sender\` / \`content\` 的，就当成普通文本聊一句
（落在当前会话里）。

### 结果在哪看

「打开 URL」是单向的，这一轮的回复**不会**回到快捷指令里，它在：

- 普通文本 → 当前会话里；
- 通知 → 那条「App + 发件人」会话里（App 会直接跳过去，生成过程实时可见），
  同时留一份在「记录」页。

想真正做到「自动回复到群里」，让 AI 去调那条**发送**快捷指令就行 ——
它现在在前台，触发快捷指令是正常的。

`
}

export function notifyDocMarkdown(scriptName: string): string {
  const name = (scriptName ?? "").trim() || "智能体"
  return `## 它能做什么、不能做什么

iOS 不允许第三方脚本读取别的 App 的通知内容，所以**它不监听微信 / 钉钉**。分工是：

- **快捷指令**负责把消息原文交进来；
- **它**负责拿到消息之后的事：每个发件人单独的记忆、人设、知识库 / 技能 / 工具、失败重试、写进本页的记录。

它只产出**回复文本**，不会替你发出去（原因见最后一节）。

## 第一步：建一条快捷指令

1. 打开「快捷指令」App → 新建
2. 加动作 **「打开 URL」**，内容是
   \`scripting://run/${name}?message=<URL 编码后的通知 JSON>\`（格式见下）
3. 运行时 Scripting 被拉到前台，AI 在前台处理这条通知

用「打开 URL」而不是「运行脚本」，是因为它要动手时得去拉起别的快捷指令，而后台进程拉不起别的 App。
详见后面「怎么把消息送进智能体」一节。

## 第二步：输入格式

\`\`\`json
${NOTIFY_TEMPLATE_JSON}
\`\`\`

| 字段 | 必填 | 说明 | 也可以写成 |
| --- | --- | --- | --- |
| \`app\` | 是 | 来源 App，记忆按它分组 | \`sourceApp\` \`bundle\` \`package\` \`来源应用\` |
| \`sender\` | 是 | 发件人，记忆按它分组 | \`from\` \`user\` \`name\` \`发件人\` \`发送人\` |
| \`content\` | 是 | 消息正文 | \`message\` \`text\` \`body\` \`内容\` \`发件内容\` |
| \`messageId\` | 否 | 同一条消息的唯一 ID，有就填，去重更准 | \`msgId\` \`notificationId\` \`id\` \`消息ID\` |

前三项缺任何一项都不当通知处理，会退回成「普通聊天」（把整段输入当成一句话发给模型）。

## 第三步：消息从哪来

| 方式 | 自动化程度 | 怎么做 |
| --- | --- | --- |
| 手动 / 分享表单 | 半自动 | 复制消息，跑快捷指令，把正文填进 \`content\` |
| 个人自动化「打开某 App」 | 半自动 | 触发时跑一条脚本读剪贴板，你复制一下消息即可 |
| 第三方转发 | 全自动 | 让消息先落到某个能发 webhook / 能写文件的中间人，再由快捷指令取 |

系统层没有「收到某 App 的通知就触发」这种能力，只能走上面这些路。

## 送进来之后发生了什么

1. **入队**：立刻处理；一次处理不完的留在队列里，App 打开时会自动接着排空（一次最多跑 80 秒）。
2. **去重**：有 \`messageId\` 按 ID 判重；没有就用「App + 发件人 + 正文」当指纹。2 分钟内重复的丢掉，已经处理过的那条 7 天内再送也算重复。
3. **排队串行**：通知、App 打开、快捷指令三路同时进来，同一时刻只有一个消费者，不会重复回同一条。
4. **分段记忆**：按「App + 发件人」各用一段会话（标题自动叫「张三（微信）」），张三和李四的记忆互不串味。
5. **记忆维护**：超过 30 天没说话就清空重来；攒到 36 条自动压缩成一段摘要，只保留最近 14 条原文。
6. **跑一轮**：用设置里的模型 + 性格与角色 + 知识库 / 技能 / 工具（要动手就调对应工具）。
7. **记录**：完成的消息会出现在本页，按 App → 联系人分组。
8. **失败重试**：自动试 4 次，间隔 15 秒 / 1 分钟 / 3 分钟 / 10 分钟；4 次都失败就进本页的「处理失败」，可以手动重试或丢掉。

## 回复怎么发回去

回复先落在 App 里（聊天页 / 本页的记录）。要真的发出去，让 AI 调一条**发送**快捷指令工具
（它在前台，能正常触发）——**钉钉群**接「自定义机器人」webhook 就能真自动回；
**微信个人对话**没有公开接口，实际只能弹通知提醒你自己发，或复制到剪贴板。

${urlEntryDoc(name)}

## 常见问题

- **提示「请先填写 API Key」**：设置 → 模型配置里还没配好供应商，通知会原样留在队列里等着。
- **提示「消息已入队」**：这一轮没轮到它（超时或正在处理别的），下次触发或打开 App 会继续。
- **提示「已处理过同一条通知」**：被去重拦下了，确认是不是重复触发。
- **一直失败**：看本页「处理失败」里的错误摘要，多半是网络或模型返回出错；点「重试」再试一次。
`
}
